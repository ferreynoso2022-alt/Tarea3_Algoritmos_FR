    private void btnActualizarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActualizarActionPerformed
        String tituloBuscado = txtBuscarAlbum.getText().trim();
        String nuevoAnioTexto = txtNuevoAnio.getText().trim();

        if (tituloBuscado.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Ingrese el titulo del album que desea actualizar.");
            txtBuscarAlbum.requestFocus();
            return;
        }

        indiceEncontrado = buscarIndice(tituloBuscado);

        if (indiceEncontrado == -1) {
            JOptionPane.showMessageDialog(this,"No se puede actualizar. Album no encontrado.");
            return;
        }

        if (nuevoAnioTexto.isEmpty()) {
            JOptionPane.showMessageDialog(this,"Ingrese el nuevo año de lanzamiento.");
            txtNuevoAnio.requestFocus();
            return;
        }

        int nuevoAnio;

        try {
            nuevoAnio = Integer.parseInt(nuevoAnioTexto);

            if (nuevoAnio <= 0) {
                JOptionPane.showMessageDialog(this,"El año debe ser un numero positivo.");
                return;
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this,"Ingrese un año valido usando numeros.");
            txtNuevoAnio.requestFocus();
            return;
        }

        anios[indiceEncontrado] = nuevoAnio;

        try (PrintWriter pw = new PrintWriter(new FileWriter(ruta, false))) {

            for (int i = 0; i < cantidadDiscos; i++) {
                pw.println(titulos[i] + "," + anios[i]);
            }

            lblResultadoAnio.setText(
            String.valueOf(nuevoAnio));

            JOptionPane.showMessageDialog(this,"Registro actualizado correctamente.");
            txtNuevoAnio.setText("");

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this,"Error al guardar los cambios: " + e.getMessage());
        }
    }

    private void btnBuscarActionPerformed(java.awt.event.ActionEvent evt) {                                          
        String tituloBuscado = txtBuscarAlbum.getText().trim();

        if (tituloBuscado.isEmpty()) {
            JOptionPane.showMessageDialog(this,
                    "Ingrese el titulo del album.");
            txtBuscarAlbum.requestFocus();
            return;
        }

        indiceEncontrado = buscarIndice(tituloBuscado);

        if (indiceEncontrado != -1) {

            lblResultadoAnio.setText(
                    String.valueOf(anios[indiceEncontrado]));

            txtNuevoAnio.setText(
                    String.valueOf(anios[indiceEncontrado]));

        } else {

            lblResultadoAnio.setText("No encontrado");
            txtNuevoAnio.setText("");

            JOptionPane.showMessageDialog(this,
                    "El album no se encuentra registrado.");
        }
    }

