    private void cargarDiscos() {
        File carpeta = new File("temp");
        File archivo = new File(ruta);

        try {
        
            if (!carpeta.exists()) {
                carpeta.mkdirs();
            }

            if (!archivo.exists()) {
                try (PrintWriter pw = new PrintWriter(new FileWriter(archivo, false))) {
                    pw.println("Thriller,1982");
                    pw.println("Back in Black,1980");
                    pw.println("Abbey Road,1969");
                    pw.println("Nevermind,1991");
                    pw.println("The Dark Side of the Moon,1973");
                }
            }

            cantidadDiscos = 0;

            try (Scanner sc = new Scanner(archivo)) {

                while (sc.hasNextLine() && cantidadDiscos < titulos.length) {
                    String linea = sc.nextLine().trim();

                    if (linea.isEmpty()) {
                        continue;
                    }

                    String[] datos = linea.split(",");

                    if (datos.length == 2) {
                        try {
                            String titulo = datos[0].trim();
                            int anio = Integer.parseInt(datos[1].trim());

                            titulos[cantidadDiscos] = titulo;
                            anios[cantidadDiscos] = anio;

                            cantidadDiscos++;

                        } catch (NumberFormatException e) {
                            System.out.println("Se omitio un registro con año invalido.");
                        }
                    }
                }
            }

        } catch (IOException e) {
            JOptionPane.showMessageDialog(this,"Error al cargar los discos: " + e.getMessage());
        }
    }

    private int buscarIndice(String tituloBuscado) {
        for (int i = 0; i < cantidadDiscos; i++) {

            if (titulos[i].equalsIgnoreCase(tituloBuscado.trim())) {
                return i;
            }
        }

        return -1;
    }

