    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {
        int calidos = 0;
        int frescos = 0;
        double total = 0;
        double promedio;

        for (int i = 0; i < temperaturas.length; i++) {
            double temperatura = temperaturas[i];
            total += temperatura;

            if (temperatura != 0.0) {
                if (temperatura >= 25.0) {
                    calidos++;
                } else {
                    frescos++;
                }
            }

        }

        promedio = total/indice;

        txtAreaResultados.append("Analisis Climatico"+"\n");
        txtAreaResultados.append("--------------"+"\n");
        txtAreaResultados.append("Promedio de temperatura: "+promedio+"\n");
        txtAreaResultados.append("Dias Calidos: "+calidos+"\n");
        txtAreaResultados.append("Dias Frescos: "+frescos+"\n");


    }

