    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarActionPerformed
        String textoKilometro = txtKilometraje.getText();
        double kilometro = Double.parseDouble(textoKilometro);

        if (indice == 7) {
            JOptionPane.showMessageDialog(this, "Llegaste al limite de dias");
            txtKilometraje.setText("");
        } else {
            kilometrajes[indice] = kilometro;
            indice++;
            txtKilometraje.setText("");
        }

    }

    private void btnReporteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnReporteActionPerformed
        double total = 0;
        double promedio = 0; 
        int conteo = 0;

        for (int i = 0; i < kilometrajes.length; i++) {
            if (kilometrajes[i]!=0) {
                total += kilometrajes[i];
                conteo++;
            }

        }

        promedio = total/conteo;
        
        try (FileWriter fw = new FileWriter(ubicacion)) {
            fw.append("Reporte Semanal Rutas \n");
            fw.append("Total Kilometros: "+ total + "\n");
            fw.append("Promedio Diario: " + promedio + "\n");
            fw.append("\n");
            fw.append("Dias Registrados:"+ conteo);
        } catch (IOException e) {
            System.out.println("Ocurrio un error de al escribir o leer");
        }
    }

