    private void btnAgregarActionPerformed(java.awt.event.ActionEvent evt) {                                           
        String tarea = txtTarea.getText();

        if (indice == 5) {
            JOptionPane.showMessageDialog(this, "Llegaste al limite de tareas");
            txtTarea.setText("");
        } else {
            tareas[indice] = tarea;
            indice++;
            txtTarea.setText("");
            txtAreaTareas.setText("Agenda de tareas"+ "\n");

            for (int i = 0; i < tareas.length; i++) {
            if (tareas[i]!= null) {
                txtAreaTareas.append((i+1)+"." + tareas[i] + "\n");
            }
        }
        }

    }

    private void btnExportarActionPerformed(java.awt.event.ActionEvent evt) {                                            
        try (FileWriter fw = new FileWriter(ubicacion, true)) {
            fw.append("Agenda de Tareas:"+ "\n");

            for (int i = 0; i < tareas.length; i++) {
                if (tareas[i]!= null) {
                    fw.append((i+1)+"." + tareas[i] + "\n");
                }

            }
            
        } catch (IOException e) {
            System.out.println("Ocurrio un error de lectura o escritura");
        }
    }

