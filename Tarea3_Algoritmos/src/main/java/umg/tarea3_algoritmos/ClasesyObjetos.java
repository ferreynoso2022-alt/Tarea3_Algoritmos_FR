    public void CrearArtista(){
        String nombre = txtNombre.getText();
        String pais = txtPais.getText();
        int oyentes = Integer.parseInt(txtOyentes.getText());

        Artista artista = new Artista(nombre, pais, oyentes);

        txtAreaRegistros.append("Artista Creado"+"\n");
        txtAreaRegistros.append(artista.nombre+" | "+artista.pais+" | "+artista.oyentes+"\n");

        txtNombre.setText("");
        txtPais.setText("");
        txtOyentes.setText("");

    }

    public void CrearCancion(){
        String titulo = txtTitulo.getText();
        String interprete = txtInterprete.getText();
        int duracion = Integer.parseInt(txtDuracion.getText());
        String genero = txtGenero.getText();

        Cancion cancion = new Cancion(titulo, interprete, duracion, genero);

        txtAreaRegistros.append("Cancion Creada"+"\n");
        txtAreaRegistros.append(cancion.titulo+" | "+cancion.interprete+" | "+"Duracion: "+cancion.duracion+" seg"+" | "+cancion.genero+"\n");

        txtTitulo.setText("");
        txtInterprete.setText("");
        txtDuracion.setText("");
        txtGenero.setText("");

    }

